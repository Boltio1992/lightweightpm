#!/usr/bin/env node
/**
 * Regenerates two artefacts from supabase/schema.sql + supabase/migrations:
 *
 *   1. supabase/schema-manifest.json — the columns LightPM expects, used by
 *      scripts/check-db-schema.js and app/api/health/schema to diff against a
 *      live database.
 *   2. supabase/migrations/<today>_sync_all_columns.sql — an idempotent
 *      "catch-up" migration that adds every expected column that an older
 *      database is missing, then reloads the PostgREST schema cache.
 *
 * Run it whenever you change the schema:  npm run db:manifest
 */

const fs = require("fs");
const path = require("path");
const { parseSqlSchema, ROOT } = require("./lib/schema-parse");

const schema = parseSqlSchema();
const tables = Object.keys(schema).sort();

/* ---------------------------------------------------------- 1. manifest JSON */

const manifest = {
  note: "Generated by scripts/gen-schema-manifest.js from supabase/schema.sql + migrations. Do not edit by hand.",
  generatedAt: new Date().toISOString().slice(0, 10),
  tables: {},
};

for (const table of tables) {
  manifest.tables[table] = {};
  for (const col of Object.keys(schema[table]).sort()) manifest.tables[table][col] = schema[table][col];
}

const manifestPath = path.join(ROOT, "supabase", "schema-manifest.json");
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");

/* ------------------------------------------------- 2. catch-up migration SQL */

const SKIP_DEFS = /primary\s+key/i;
const lines = [];
lines.push("-- Generated by scripts/gen-schema-manifest.js — safe to run more than once.");
lines.push("--");
lines.push("-- Brings an older database up to date with supabase/schema.sql: every column the");
lines.push("-- app writes is added if missing. This is the fix for the recurring");
lines.push("-- \"Could not find the '<column>' column of '<table>' in the schema cache\" errors,");
lines.push("-- which silently drop fields on insert (see lib/resilientInsert.ts).");
lines.push("");

for (const table of tables) {
  const cols = Object.keys(schema[table])
    .filter((c) => c !== "id")
    .filter((c) => !SKIP_DEFS.test(schema[table][c]))
    .sort();
  if (!cols.length) continue;
  lines.push(`alter table ${table}`);
  cols.forEach((col, i) => {
    const comma = i === cols.length - 1 ? ";" : ",";
    // `not null` without a default fails on a table that already has rows, so
    // relax it here: the point of this migration is that the column EXISTS, not
    // that it is already constrained.
    let def = schema[table][col];
    if (/\bnot\s+null\b/i.test(def) && !/\bdefault\b/i.test(def)) def = def.replace(/\bnot\s+null\b/gi, "").replace(/\s+/g, " ").trim();
    lines.push(`  add column if not exists ${col} ${def}${comma}`);
  });
  lines.push("");
}

lines.push("-- Make PostgREST pick up every new column immediately, otherwise the schema");
lines.push("-- cache keeps serving the old shape and the API keeps 400ing.");
lines.push("notify pgrst, 'reload schema';");
lines.push("");

const stamp = new Date().toISOString().slice(0, 10).replace(/-/g, "");
const migrationPath = path.join(ROOT, "supabase", "migrations", `${stamp}_sync_all_columns.sql`);
fs.writeFileSync(migrationPath, lines.join("\n"));

console.log(`wrote ${path.relative(ROOT, manifestPath)}`);
console.log(`wrote ${path.relative(ROOT, migrationPath)}`);
console.log(`tables: ${tables.join(", ")}`);
